export type AdminLanguage = keyof typeof adminTranslations

export function adminT(language: AdminLanguage, key: string) {
  const keys = key.split(".")
  let result: any = adminTranslations[language]

  for (const item of keys) {
    result = result?.[item]
    if (!result) return key
  }

  return result as string
}

export function adminStatusT(language: AdminLanguage, status: string) {
  const direct = status.toLowerCase().replace(/\s+/g, "_")
  const keyMap: Record<string, string> = {
    active: "active",
    inactive: "inactive",
    blocked: "blocked",
    published: "published",
    draft: "draft",
    disabled: "disabled",
    deleted: "deleted",
    paid: "paid",
    unpaid: "unpaid",
    pending: "pending",
    approved: "approved",
    rejected: "rejected",
    cancelled: "cancelled",
    canceled: "cancelled",
    refunded: "refunded",
    confirmed: "confirmed",
    checked_in: "checkedIn",
    checked: "checkedIn",
    not_checked: "notChecked",
    registered: "registered",
    sent: "sent",
    ready: "ready",
    waiting: "waiting",
  }
  const translated = adminT(language, `status.${keyMap[direct] || direct}`)
  return translated.startsWith("status.") ? status.replace(/_/g, " ") : translated
}
